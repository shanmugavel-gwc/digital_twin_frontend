import { chromium } from "playwright";
import fs from "node:fs";
const env = fs.readFileSync("../backend/.env", "utf8");
const url = new URL(env.match(/^NEON_READONLY_URL=(.*)$/m)[1].trim().replace("postgresql+psycopg", "postgresql"));
const pw = decodeURIComponent(url.password);
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 1100 } });
const errs = [], leaks = []; p.on("pageerror", (e) => errs.push(e.message));
p.on("response", async (r) => { if (r.url().includes("/api/")) { try { if ((await r.text()).includes(pw)) leaks.push(r.url()); } catch {} } });
await p.goto(`${process.env.UI_URL}/#connectors`); await p.waitForSelector(".addconn", { timeout: 30000 });
await p.selectOption(".addconn select >> nth=0", "postgres");
await p.fill('input[name="postgres-host"]', url.hostname); await p.fill('input[name="postgres-port"]', url.port || "5432");
await p.fill('input[name="postgres-database"]', url.pathname.slice(1)); await p.fill('input[name="postgres-username"]', decodeURIComponent(url.username));
await p.fill('input[name="postgres-password"]', pw);
await p.click("button:has-text('Test and connect')");
await p.waitForSelector(".addconn p.note", { timeout: 60000 });
console.log("connect note:", (await p.$eval(".addconn p.note", (e) => e.textContent)).slice(0, 140));
console.log("password field after submit is empty:", (await p.inputValue('input[name="postgres-password"]')) === "");
await p.waitForSelector(".conn:has-text('PostgreSQL') .badge:has-text('CONNECTED (this session)')", { timeout: 20000 });
const card = p.locator(".conn:has-text('PostgreSQL database')");
await card.locator("button:has-text('List tables')").click();
await card.locator("select").waitFor({ timeout: 60000 });
await card.locator("select").selectOption("twin.dim_machine");
await card.locator("table.data").waitFor({ timeout: 60000 });
console.log("preview rows:", await card.locator("table.data tbody tr").count(), "| header:", (await card.locator("table.data thead th").allTextContents()).slice(0, 4));
await p.screenshot({ path: process.env.OUT + "/addconn.png", fullPage: true });
console.log("password present in page HTML:", (await p.content()).includes(pw), "| in any API response:", leaks.length ? leaks : "no");
await card.locator("button:has-text('Disconnect')").click(); await p.waitForSelector(".conn:has-text('PostgreSQL') .badge:has-text('NOT CONNECTED')", { timeout: 20000 });
console.log("after disconnect: NOT CONNECTED | js errors:", errs.length ? errs : "none");
await b.close();
